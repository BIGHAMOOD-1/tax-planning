# ────────────────────── 基础工具 ──────────────────────

def _font(run, name, size, bold=False, color=None):
    run.font.name = name
    run._element.rPr.rFonts.set(qn("w:eastAsia"), name)
    run.font.size = Pt(size)
    run.font.bold = bold
    if color:
        run.font.color.rgb = RGBColor.from_string(color)


def _setup(doc: Document):
    sec = doc.sections[0]
    sec.page_width, sec.page_height = Cm(21.0), Cm(29.7)
    sec.top_margin, sec.bottom_margin = Cm(3.7), Cm(3.5)
    sec.left_margin, sec.right_margin = Cm(2.8), Cm(2.6)
    st = doc.styles["Normal"]
    st.font.name = F_BODY
    st.font.size = Pt(SZ_BODY)
    st.element.rPr.rFonts.set(qn("w:eastAsia"), F_BODY)
    # 页脚页码
    footer_p = sec.footer.paragraphs[0]
    footer_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    _font(footer_p.add_run("— "), F_BODY, 10.5)
    _page_number(footer_p)
    _font(footer_p.add_run(" —"), F_BODY, 10.5)


def _page_number(p):
    run = p.add_run()
    _font(run, F_BODY, 10.5)
    a = OxmlElement("w:fldChar"); a.set(qn("w:fldCharType"), "begin")
    b = OxmlElement("w:instrText"); b.set(qn("xml:space"), "preserve"); b.text = "PAGE"
    c = OxmlElement("w:fldChar"); c.set(qn("w:fldCharType"), "end")
    run._r.append(a); run._r.append(b); run._r.append(c)


def _para(doc, text, name=F_BODY, size=SZ_BODY, bold=False, indent=True,
          align=None, space_after=0, line=LINE):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.line_spacing_rule = WD_LINE_SPACING.EXACTLY
    pf.line_spacing = Pt(line)
    pf.space_before = Pt(0)
    pf.space_after = Pt(space_after)
    if indent:
        pf.first_line_indent = Pt(size * 2)
    if align is not None:
        p.alignment = align
    _font(p.add_run(text), name, size, bold)
    return p


def h1(doc, text):
    return _para(doc, text, F_H1, SZ_BODY, bold=False, indent=True)


def h2(doc, text):
    return _para(doc, text, F_H2, SZ_BODY, bold=False, indent=True)


def body(doc, text):
    return _para(doc, text, F_BODY, SZ_BODY, indent=True)


