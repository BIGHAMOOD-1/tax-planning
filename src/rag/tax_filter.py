DEFAULT_TAX_TYPES = ["税收政策-企业所得税", "税费征管"]


def allowed_tax_types(direction: str | None) -> list[str]:
    """返回该方向允许的 tax_type 列表（含空白，避免漏掉未标注政策）。"""
    base = DIRECTION_TAX_TYPES.get(str(direction or "").strip(), DEFAULT_TAX_TYPES)
    return list(dict.fromkeys([*base, EMPTY_OK]))


def policy_filters(direction: str | None) -> dict:
    return {"tax_type": allowed_tax_types(direction)}
